import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export function fontPath() {
  const path = fileURLToPath(
    new URL(
      "../../excalidraw/node_modules/@excalidraw/utils/dist/prod/assets/Excalifont.ttf",
      import.meta.url,
    ),
  );
  return existsSync(path) ? path : undefined;
}

// Read only the sfnt tables needed for advances; no outlines or shaping.
export function advances(path) {
  const b = readFileSync(path);
  const u16 = (p) => b.readUInt16BE(p);
  const i16 = (p) => b.readInt16BE(p);
  const u32 = (p) => b.readUInt32BE(p);
  const tables = {};
  for (let p = 12; p < 12 + u16(4) * 16; p += 16)
    tables[b.toString("ascii", p, p + 4)] = u32(p + 8);
  const cmap = tables.cmap;
  const maps = [];
  for (let p = cmap + 4; p < cmap + 4 + u16(cmap + 2) * 8; p += 8) {
    const at = cmap + u32(p + 4);
    if (u16(at) === 4 || u16(at) === 12) maps.push(at);
  }
  const at = maps.find((p) => u16(p) === 12) ?? maps[0];
  if (at === undefined) throw new Error("Font has no supported Unicode cmap");
  function glyph(cp) {
    if (u16(at) === 12) {
      for (let p = at + 16; p < at + 16 + u32(at + 12) * 12; p += 12)
        if (cp >= u32(p) && cp <= u32(p + 4)) return u32(p + 8) + cp - u32(p);
    } else {
      const n = u16(at + 6) / 2;
      for (let i = 0; i < n; i++) {
        const end = u16(at + 14 + i * 2);
        const start = u16(at + 16 + n * 2 + i * 2);
        if (cp < start || cp > end) continue;
        const delta = i16(at + 16 + n * 4 + i * 2);
        const rp = at + 16 + n * 6 + i * 2;
        const offset = u16(rp);
        const g = offset ? u16(rp + offset + (cp - start) * 2) : cp;
        return offset && !g ? 0 : (g + delta) & 65535;
      }
    }
    return 0;
  }
  const widths = new Map();
  for (const range of RANGES.split(",")) {
    const [a, z] = range.split("-").map((h) => parseInt(h, 16));
    for (let cp = a; cp <= (z ?? a); cp++) {
      const g = glyph(cp);
      if (g) widths.set(cp, u16(tables.hmtx + Math.min(g, u16(tables.hhea + 34) - 1) * 4));
    }
  }
  const runs = [];
  for (const [cp, w] of [...widths].sort((a, b) => a[0] - b[0])) {
    const last = runs.at(-1);
    if (last && last[0] + last.length - 1 === cp) last.push(w);
    else runs.push([cp, w]);
  }
  return {
    runs,
    unitsPerEm: u16(tables.head + 18),
    ascent: i16(tables.hhea + 4),
    descent: -i16(tables.hhea + 6),
    fallbackAdvance: Math.round([...widths.values()].reduce((a, b) => a + b, 0) / widths.size),
  };
}

// Unicode ranges of the seven Excalifont web subsets.
const RANGES =
  "20-7e,a0-a3,a5-a6,a8-ab,ad-b1,b4,b6-b8,ba-ff,131,152-153,2bc,2c6,2da,2dc,304,308,2013-2014,2018-201a,201c-201e,2020,2022,2024-2026,2030,2039-203a,20ac,2122,2212," +
  "100-130,132-137,139-149,14c-151,154-17e,192,1fc-1ff,218-21b,237,1e80-1e85,1ef2-1ef3,2113," +
  "400-45f,490-491,2116,37e,384-38a,38c,38e-393,395-3a1,3a3-3a8,3aa-3cf,3d7," +
  "2c7,2d8-2d9,2db,2dd,302,306-307,30a-30c,326-328,212e,2211,fb01-fb02,462-463,472-475,4d8-4d9,4e2-4e3,4e6-4e9,4ee-4ef,300-301,303";

export async function generate() {
  const path = fontPath();
  if (!path) throw new Error("Install @excalidraw/utils to regenerate Excalifont metrics");
  const font = advances(path);
  return `// Generated by packages/core/scripts/metrics.mjs from Excalifont.ttf in @excalidraw/utils 0.1.8
// (Excalifont Regular 1.000, SIL OFL 1.1), limited to the web font's unicode ranges.
import type { FontMetrics } from "./metrics.js";
import { EXCALIFONT_KERNING } from "./metrics-excalifont-kerning.js";

export const EXCALIFONT: FontMetrics = {
  name: "Excalifont",
  kerning: EXCALIFONT_KERNING,
  unitsPerEm: ${font.unitsPerEm},
  ascent: ${font.ascent},
  descent: ${font.descent},
  /** Excalidraw's line height for font family 5. */
  lineHeight: 1.25,
  /** Width used for characters outside the table (drawn by a fallback font). */
  fallbackAdvance: ${font.fallbackAdvance},
  /** Runs of consecutive code points: [first code point, advance, advance, ...]. */
  runs: ${JSON.stringify(font.runs)},
};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  writeFileSync(new URL("../src/metrics-excalifont.ts", import.meta.url), await generate());
