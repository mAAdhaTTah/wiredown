import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { CATALOG, COMMON_FLAGS, ICON_NAMES } from "../packages/core/dist/index.js";

// The catalog's components, by category: one reference file each, so an
// agent reads only the categories a screen needs.
const CATEGORIES = [
  {
    file: "layout",
    title: "Layout and containers",
    types: [
      "window",
      "dialog",
      "browser",
      "phone",
      "box",
      "row",
      "columns",
      "section",
      "tabs",
      "form",
      "field",
      "details",
    ],
  },
  {
    file: "inputs",
    title: "Inputs and actions",
    types: [
      "button",
      "buttons",
      "input",
      "search",
      "password",
      "textarea",
      "dropdown",
      "checkbox",
      "radio",
      "toggle",
      "slider",
    ],
  },
  {
    file: "content",
    title: "Text, media and feedback",
    types: [
      "text",
      "h1",
      "h2",
      "paragraph",
      "link",
      "icon",
      "avatar",
      "image",
      "placeholder",
      "alert",
      "progress",
      "tooltip",
      "spin",
    ],
  },
  {
    file: "data",
    title: "Data and navigation",
    types: ["grid", "tree", "nav", "menu", "breadcrumb", "pagination"],
  },
  {
    file: "variants",
    title: "Variants",
    types: ["extends", "replace", "remove", "after", "before", "rows"],
  },
];

const GENERATED =
  "<!-- Generated by pnpm skill: component sections from core's catalog, the rest written in scripts/skill.mjs. Do not edit. -->";

// The syntax reference, by path under skills/wiredown/reference/: the
// grammar and an index in syntax.md, then one file per category. Component
// sections come from core's catalog; the rest is written here, and the
// skill tests check its examples.
export function skillReference() {
  const listed = CATEGORIES.flatMap((category) => category.types);
  const unlisted = CATALOG.filter((entry) => !listed.includes(entry.type)).map(
    (entry) => entry.type,
  );
  const twice = listed.filter((type, index) => listed.indexOf(type) !== index);
  if (unlisted.length || twice.length || listed.length !== CATALOG.length) {
    throw new Error(
      `each catalog entry needs one category: unlisted ${unlisted}, listed twice ${twice}`,
    );
  }
  const entry = (type) => CATALOG.find((candidate) => candidate.type === type);
  const containers = CATALOG.filter((entry) => entry.container && !entry.directive)
    .map((entry) => entry.keywords[0])
    .join(", ");
  const section = (entry) => {
    const options = [
      ...entry.flags.map((flag) => `\`${flag}\``),
      ...entry.numbers.map((number) => `\`${number}=number\``),
    ];
    return `## ${entry.keywords[0]}

Keywords: ${entry.keywords.map((word) => `\`${word}\``).join(", ")}.

${entry.description}

Content: ${entry.content ? "yes" : "no"}. Container: ${entry.container ? "yes" : "no"}.
Options: ${options.join(", ") || "none"}.${entry.directive ? " No common flags or id." : " Also takes the common flags and an id."}

\`\`\`text
${entry.example}
\`\`\`
`;
  };
  const index = CATEGORIES.map(
    (category) =>
      `- [${category.title}](components/${category.file}.md): ${category.types.map((type) => `\`${entry(type).keywords[0]}\``).join(", ")}`,
  ).join("\n");
  const extra = {
    content: `
## Icons

${ICON_NAMES.map((name) => `\`${name}\``).join(", ")}.
`,
    variants: `
## Variants

Start with extends: screen-id. Use replace: id with exactly one indented
component (it inherits the id; with no children of its own and the
target's type, it keeps the target's children), remove: id (comma-separated ids allowed),
after: id or before: id with indented additions, and rows: grid-id with
indented rows. In rows, = keeps a cell and remove <row-key> removes a row.
Here is a base screen and a variant using every verb:

\`\`\`wiredown
window: Members
  text: Original #title
  text: Temporary #temporary
  grid #target
  Name | Status
  Anna | Invited
  Erik | Active
\`\`\`

^base

\`\`\`wiredown
extends: base
replace: title
  text: Updated
remove: temporary
before: target
  text: Before table
after: target
  text: After table
rows: target
  Anna | Active
  remove Erik
\`\`\`

^updated
`,
  };
  return {
    "syntax.md": `${GENERATED}

# Syntax

Write one component per line: keyword: content #id (options).
Indent children by two spaces. Continuation lines hold grid rows or more
content; a blank line ends continuation. Options go last, comma-separated.
Common flags: ${COMMON_FLAGS.map((flag) => `\`${flag}\``).join(", ")}.
Use #name for ids (lowercase letter, then lowercase letters, digits or hyphens).
The alternative (id=name) also works. Directives take neither ids nor options.
Only ${containers} may contain indented components.
Others report e.g. "text" can't contain other components (followed by the
allowed container list). Lines starting with // are comments.
A leading * makes buttons primary, tabs selected and nav items active.
Inline {icon}, [link] and -grey text- draw icons, links and grey text in
supported labels (for example alert and button).
Tree lines use + for closed branches, - for open branches and * for selection;
indentation gives their depth. Nav and menu use a lone - item as a divider;
menu lines are label | shortcut.

Grids fill their container by default; (fit) opts out. The first row is the
header. Cells split on |, or commas when no row uses |. [x] and [ ] cells
draw checked and unchecked boxes. Prefix a row with * for selection, > for
an action outline, or >* for both (put a space before the first cell).
Numeric data cells align right. Rows shorter than the header are accepted.
In a variant's rows: patch, the row key is the first cell that is not a
checkbox or =, and must match exactly one row (no match adds the row).
Change each row at most once per patch. = keeps a cell and remove <row-key>
removes a row. A patch may leave out the checkbox cell, and then starts at
the key column; a new row gets an unchecked box when the last row has one.
A patch may not have more cells than the grid has columns.

A field wraps one non-container component: field: Label | component: content.
Put its #id and options after the inner content; the id names the whole
field. Inner options stay on the component; floating, required and fill
also apply to the field, and disabled greys its label too.

Save this complete example in screens.md (including its fence and block id):

\`\`\`wiredown
window: Settings
  tabs: *Profile | Security
    // Two labelled controls
    form: Contact
      field: Name | input: Ada #name (required)
      field: Country | dropdown: *Sweden | Norway #country
    grid #people
    [ ] | Name | Count
    * [x] | Ada | 12
    > [ ] | Bea | 3
    >* [ ] | Cy
    alert: {info} Saved. [Undo] -Pending-
    buttons: Cancel | *Save
    nav: *Home | - | Settings
    menu: Copy | Ctrl+C
    -
    Paste | Ctrl+V
    tree: - {folder} Project
      + {folder} docs
      * Readme
    text: Visible (xyzzy)
    grid: Name, Count
    Ada, 12
\`\`\`

^grammar

A parenthesised word that is not a known option stays visible text. A distant
misspelling such as (xyzzy) is NOT reported by check; inspect the PNG.

## Escapes

Write \\( to keep a trailing option-like parenthesis literal, and \\# to
keep a trailing id-like token literal. Other parentheses remain text unless
recognized as options; C# and Step #3 remain text.

## Components

Each category's file has its components' keywords, options and an example.
Read only the files for the components a screen uses.

${index}
`,
    ...Object.fromEntries(
      CATEGORIES.map((category) => [
        `components/${category.file}.md`,
        `${GENERATED}

# ${category.title}

${category.types.map((type) => section(entry(type))).join("\n")}${extra[category.file] ?? ""}`,
      ]),
    ),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const directory = new URL("../skills/wiredown/reference/", import.meta.url);
  mkdirSync(new URL("components/", directory), { recursive: true });
  for (const [path, text] of Object.entries(skillReference())) {
    writeFileSync(new URL(path, directory), text);
  }
}
